const W = 128;
const H = 160;

const LIGHT_PALETTE: Record<number, string | null> = {
    0: null,
    1: '#f5f3ee',
    2: '#141414',
    3: '#cdcbc6',
};

const DARK_PALETTE: Record<number, string | null> = {
    0: null,
    1: '#292929',
    2: '#e7e5df',
    3: '#77746f',
};

const SHADOW = { cx: 73.5, cy: 152.5, rx: 20, ry: 3.2 };

interface PixelPetProps {
    scale?: number;
    className?: string;
}

export default function CatronautIdle({ scale = 3, className }: PixelPetProps) {
    const canvasRef = useRef<HTMLCanvasElement>(null);
    const rafRef = useRef<number>(0);

    useEffect(() => {
        const canvas = canvasRef.current;

        if (!canvas) return;

        const ctx = canvas.getContext('2d');

        if (!ctx) return;

        ctx.imageSmoothingEnabled = false;

        const drawCharacter = () => {
            const isDark = document.documentElement.classList.contains('dark');

            const palette = isDark ? DARK_PALETTE : LIGHT_PALETTE;

            for (let y = 0; y < H; y++) {
                for (let x = 0; x < W; x++) {
                    const v = GRID[y][x];
                    const color = palette[v];

                    if (!color) continue;

                    ctx.fillStyle = color;
                    ctx.fillRect(x, y, 1, 1);
                }
            }
        };

        const drawShadow = (scaleFactor: number) => {
            ctx.fillStyle = document.documentElement.classList.contains('dark')
                ? 'rgba(0,0,0,0.35)'
                : 'rgba(20,20,20,0.16)';

            ctx.beginPath();

            ctx.ellipse(SHADOW.cx, SHADOW.cy, SHADOW.rx * scaleFactor, SHADOW.ry * scaleFactor, 0, 0, Math.PI * 2);

            ctx.fill();
        };

        let t = 0;

        const AMPLITUDE = 3;

        const frame = () => {
            t += 0.045;

            const bob = Math.round(Math.sin(t) * AMPLITUDE);

            const shadowScale = 1 + (bob / AMPLITUDE) * 0.22;

            ctx.clearRect(0, 0, canvas.width, canvas.height);

            drawShadow(shadowScale);

            ctx.save();

            ctx.translate(0, bob);

            drawCharacter();

            ctx.restore();

            rafRef.current = requestAnimationFrame(frame);
        };

        frame();

        return () => {
            cancelAnimationFrame(rafRef.current);
        };
    }, []);

    return (
        <canvas
            ref={canvasRef}
            width={W}
            height={H}
            className={className}
            style={{
                width: W * scale,
                height: H * scale,
                maxWidth: 'none',
                maxHeight: 'none',
                display: 'block',
                flexShrink: 0,
                boxSizing: 'content-box',
                imageRendering: 'pixelated',
            }}
        />
    );
}
