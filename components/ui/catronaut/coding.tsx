interface CodingPetProps {
    scale?: number;
    className?: string;
}

export default function CatronautCoding({ scale = 5, className }: CodingPetProps) {
    const canvasRef = useRef<HTMLCanvasElement>(null);
    const rafRef = useRef<number>(0);

    useEffect(() => {
        const canvas = canvasRef.current;
        if (!canvas) return;
        const ctx = canvas.getContext('2d');
        if (!ctx) return;
        ctx.imageSmoothingEnabled = false;

        const drawGrid = (grid: number[][], w: number, h: number, offX: number, offY: number) => {
            for (let y = 0; y < h; y++) {
                for (let x = 0; x < w; x++) {
                    const color = PALETTE[grid[y][x]];
                    if (!color) continue;
                    ctx.fillStyle = color;
                    ctx.fillRect(x + offX, y + offY, 1, 1);
                }
            }
        };

        let t = 0;
        const HEART_CYCLE = 260;

        const frame = () => {
            t += 1;

            const hp = (t % HEART_CYCLE) / HEART_CYCLE;
            let heartY: number;
            let heartAlpha: number;

            if (hp < 0.12) {
                const p = hp / 0.12;
                heartAlpha = p;
                heartY = 0;
            } else if (hp < 0.75) {
                const p = (hp - 0.12) / 0.63;
                heartAlpha = 1;
                heartY = -Math.round(p * 4);
            } else {
                const p = (hp - 0.75) / 0.25;
                heartAlpha = 1 - p;
                heartY = -4;
            }

            ctx.clearRect(0, 0, canvas.width, canvas.height);

            drawGrid(MAIN_GRID, G, G, 0, 0);

            ctx.save();
            ctx.globalAlpha = heartAlpha;
            drawGrid(HEART_GRID, HW, HH, HX0, HY0 + heartY);
            ctx.restore();

            rafRef.current = requestAnimationFrame(frame);
        };

        frame();
        return () => cancelAnimationFrame(rafRef.current);
    }, []);

    return (
        <canvas
            ref={canvasRef}
            width={G}
            height={G}
            className={className}
            style={{
                width: G * scale,
                height: G * scale,
                maxWidth: 'none',
                maxHeight: 'none',
                display: 'block',
                flexShrink: 0,
                boxSizing: 'content-box',
                imageRendering: 'pixelated',
            }}
        />
    );
}
